-- tx_motions_open_vote.sql — governance vote OPEN as ONE Postgres
-- transaction (cutover program, Option A: Supabase write-primary for
-- the 'motions' surface behind isSupaPrimary('motions')).
--
-- Spec: ~/workspace/supabase-migration/cutover-sections/foundation.md
-- section 4 (Motions) + the H-3 / H-5 rulings in
-- ~/workspace/supabase-migration/cluster-meetings/BUILDOUT_REPORT.md.
-- Authoring rules: ./README.md. This file is an APPLY artifact:
-- authoring it applies nothing. The coordinator applies it at the
-- motions flip, AFTER the fs_tx_idempotency table exists (flip-time
-- schema step, foundation section 3).
--
-- What this replaces, on the primary path ONLY: openVote in
-- src/lib/server/governance-votes.ts, whose Firestore sequence is
--   set vote doc -> writeGovernanceAuditOrThrow (Firestore audit_logs)
--   -> update vote doc with auditLogId.
-- Here the vote row, the audit row, and the auditLogId stamp commit
-- or roll back TOGETHER (H-5 delta, primary path only): there is no
-- interleaving in which the vote exists without its audit row, or an
-- audit row exists for a vote that was never opened. The OFF path
-- keeps today's ordering byte-identically.
--
-- H-09 PRESERVED: this function performs NO permission / actor check
-- on the opener, exactly like the service it replaces. The electorate
-- is the caller-supplied frozen snapshot, stored verbatim.
--
-- LOCK ORDER (program-wide, foundation section 3): advisory lock on
-- the ENTITY first ('vote:' || p_vote_id — the SAME key
-- tx_motions_cast_vote and tx_motions_close_vote take, so open /
-- cast / close on one vote serialise across processes), then the
-- idempotency record, then the vote row FOR UPDATE.
--
-- IDEMPOTENCY: the seam mints the key at the operation's origin as
-- 'open:<voteId>' — the vote id is generated by the caller before the
-- call, so one logical open names one key and every retry of it
-- replays the recorded outcome instead of opening a second vote or
-- writing a second audit row.
--
-- Timestamps: document timestamps inside `data` jsonb are ISO-8601
-- UTC strings derived from p_timestamp (the adapter's storage
-- ruling). p_vote_data / p_audit_data arrive fully built by the seam
-- (the seam owns the document shapes, including the frozen electorate
-- snapshot and the threshold resolution — resolveThreshold stays the
-- single source in TypeScript); this function owns only atomicity,
-- serialisation, and the auditLogId stamp.

create or replace function tx_motions_open_vote(
  p_vote_id text,
  p_vote_data jsonb,
  p_audit_id text,
  p_audit_data jsonb,
  p_idempotency_key text default null,
  p_timestamp timestamptz default now()
) returns jsonb
language plpgsql
as $$
declare
  v_prior jsonb;
  v_result jsonb;
begin
  -- (A) Serialise per vote, across processes, for this transaction.
  perform pg_advisory_xact_lock(hashtextextended('vote:' || p_vote_id, 0));

  -- (B) Idempotency: replay short-circuit BEFORE any effect.
  if p_idempotency_key is not null then
    select result into v_prior
      from fs_tx_idempotency
     where key = p_idempotency_key;
    if found then
      return v_prior || jsonb_build_object('applied', false, 'duplicate', true);
    end if;
  end if;

  -- (C) Re-read under the lock: a vote row with this id already
  --     existing (and no idempotency record) is a caller error the
  --     Firestore path could not produce (ids are freshly generated);
  --     report it as a duplicate outcome rather than overwriting a
  --     live vote.
  perform 1 from fs_governance_votes where id = p_vote_id for update;
  if found then
    return jsonb_build_object(
      'applied', false, 'duplicate', true,
      'outcome', 'already_exists',
      'vote_id', p_vote_id, 'audit_log_id', null
    );
  end if;

  -- (D) Apply every effect in this one transaction: vote row, audit
  --     row, auditLogId stamp (H-5: atomic on this path).
  insert into fs_governance_votes (id, firebase_uid, parent_path, data)
  values (p_vote_id, null, 'governance_votes', p_vote_data);

  insert into fs_audit_logs (id, firebase_uid, parent_path, data)
  values (p_audit_id, null, 'audit_logs', p_audit_data);

  update fs_governance_votes
     set data = data || jsonb_build_object('auditLogId', p_audit_id)
   where id = p_vote_id;

  v_result := jsonb_build_object(
    'applied', true, 'duplicate', false,
    'outcome', 'created',
    'vote_id', p_vote_id, 'audit_log_id', p_audit_id
  );

  -- (E) Record the outcome under the idempotency key, last, in the
  --     same transaction.
  if p_idempotency_key is not null then
    insert into fs_tx_idempotency (key, fn, result)
    values (p_idempotency_key, 'tx_motions_open_vote', v_result);
  end if;

  return v_result;
end;
$$;

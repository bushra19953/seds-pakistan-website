import { jsPDF } from 'jspdf';
import { drawClickableUrl, measureUrlLines } from '@/lib/workflow-pdf-export';
import type { BalanceSheetSummary, IncomeExpenditureReport, VarianceReport } from '@/lib/finance/reports';

/**
 * Finance report PDFs (spec Part C 4.6 + 5.5). Client-side generation from
 * the reporting API JSON only, following src/lib/workflow-pdf-export.ts
 * conventions: header block, tabular body, footer with generatedBy,
 * generatedAt, FY, and a verification line. Statement Drive references are
 * rendered as visible clickable URLs via drawClickableUrl (with
 * measureUrlLines for layout), per the standing PDF rules.
 */

export interface FinancePdfMeta {
  fyLabel: string;
  generatedBy: string;
  generatedAt: string; // ISO timestamp
  asOf?: string;
  consentPending?: boolean;
  statementUrls?: string[];
}

const PAGE_W = 210;
const MARGIN = 14;
const CONTENT_W = PAGE_W - MARGIN * 2;

function pkr(n: number): string {
  return `PKR ${n.toLocaleString('en-PK')}`;
}

function header(doc: jsPDF, title: string, meta: FinancePdfMeta): number {
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('SEDS Pakistan', MARGIN, 16);
  doc.setFontSize(13);
  doc.text(title, MARGIN, 24);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(`Financial year: ${meta.fyLabel}`, MARGIN, 31);
  if (meta.asOf) doc.text(`As of: ${meta.asOf}`, MARGIN, 36);
  if (meta.consentPending) {
    doc.setTextColor(180, 60, 20);
    doc.text('NOTE: The approved budget for this FY is recorded as an interim approval; Founder Consent is pending (consentPending).', MARGIN, 41);
    doc.setTextColor(0, 0, 0);
    return 48;
  }
  return 42;
}

function footer(doc: jsPDF, meta: FinancePdfMeta): void {
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(110, 110, 110);
    doc.text(
      `Generated by ${meta.generatedBy} at ${meta.generatedAt} - FY ${meta.fyLabel} - Verify figures against the finance reporting API (exports are audit-logged). Page ${i} of ${pages}`,
      MARGIN,
      290,
    );
    doc.setTextColor(0, 0, 0);
  }
}

function table(
  doc: jsPDF,
  y: number,
  columns: Array<{ label: string; width: number; align?: 'left' | 'right' }>,
  rows: string[][],
): number {
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  let x = MARGIN;
  for (const c of columns) {
    doc.text(c.label, c.align === 'right' ? x + c.width : x, y, { align: c.align === 'right' ? 'right' : 'left' });
    x += c.width;
  }
  y += 2;
  doc.setDrawColor(160, 160, 160);
  doc.line(MARGIN, y, MARGIN + CONTENT_W, y);
  y += 5;
  doc.setFont('helvetica', 'normal');
  for (const row of rows) {
    if (y > 278) {
      doc.addPage();
      y = 16;
    }
    x = MARGIN;
    row.forEach((cell, i) => {
      const c = columns[i];
      doc.text(cell, c.align === 'right' ? x + c.width : x, y, { align: c.align === 'right' ? 'right' : 'left' });
      x += c.width;
    });
    y += 5.5;
  }
  return y;
}

function statementsBlock(doc: jsPDF, y: number, meta: FinancePdfMeta): number {
  if (!meta.statementUrls || meta.statementUrls.length === 0) return y;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('Bank statements cited', MARGIN, y);
  y += 5;
  doc.setFont('helvetica', 'normal');
  for (const url of meta.statementUrls) {
    const h = measureUrlLines(doc, url, CONTENT_W, 8);
    if (y + h > 282) {
      doc.addPage();
      y = 16;
    }
    y += drawClickableUrl(doc, url, MARGIN, y, CONTENT_W, { fontSize: 8 }) + 2;
  }
  return y;
}

export function generateIncomeExpenditurePdf(report: IncomeExpenditureReport, meta: FinancePdfMeta): jsPDF {
  const doc = new jsPDF();
  let y = header(doc, 'Income and Expenditure Statement', meta);
  y = table(
    doc,
    y,
    [
      { label: 'Category', width: 70 },
      { label: 'Income', width: 55, align: 'right' },
      { label: 'Expenditure', width: 55, align: 'right' },
    ],
    report.byCategory.map((r) => [r.category, pkr(r.incomePkr), pkr(r.expensePkr)]),
  );
  y += 2;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text(`Total income: ${pkr(report.totalIncomePkr)}`, MARGIN, y);
  y += 6;
  doc.text(`Total expenditure: ${pkr(report.totalExpensePkr)}`, MARGIN, y);
  y += 6;
  doc.text(`Net: ${pkr(report.netPkr)}`, MARGIN, y);
  statementsBlock(doc, y + 8, meta);
  footer(doc, meta);
  return doc;
}

export function generateVariancePdf(report: VarianceReport, meta: FinancePdfMeta): jsPDF {
  const doc = new jsPDF();
  let y = header(doc, 'Budget vs Actual Variance Report', meta);
  y = table(
    doc,
    y,
    [
      { label: 'Budget line', width: 62 },
      { label: 'Allocated', width: 38, align: 'right' },
      { label: 'Actual', width: 38, align: 'right' },
      { label: 'Variance', width: 44, align: 'right' },
    ],
    report.lines.map((l) => [l.label, pkr(l.allocatedPkr), pkr(l.actualPkr), pkr(l.variancePkr)]),
  );
  y += 2;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text(`Total allocated: ${pkr(report.totalAllocatedPkr)} - Total actual: ${pkr(report.totalActualPkr)}`, MARGIN, y);
  y += 6;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(`Unbudgeted posted expenditure (outside budget lines): ${pkr(report.unbudgetedPostedExpensePkr)}`, MARGIN, y);
  statementsBlock(doc, y + 8, meta);
  footer(doc, meta);
  return doc;
}

export function generateBalanceSheetPdf(report: BalanceSheetSummary, meta: FinancePdfMeta): jsPDF {
  const doc = new jsPDF();
  let y = header(doc, 'Balance Sheet Summary (Funds Held)', meta);
  y = table(
    doc,
    y,
    [
      { label: 'Account', width: 62 },
      { label: 'Opening', width: 40, align: 'right' },
      { label: 'Net movement', width: 40, align: 'right' },
      { label: 'Funds held', width: 40, align: 'right' },
    ],
    report.accounts.map((a) => [a.label, pkr(a.openingBalancePkr), pkr(a.netMovementPkr), pkr(a.fundsHeldPkr)]),
  );
  y += 2;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text(`Total funds held: ${pkr(report.totalFundsHeldPkr)}`, MARGIN, y);
  y += 7;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(
    `Note: related-party amounts recorded as posted expenses without a matched receipt total ${pkr(report.relatedPartyUnreceiptedNotePkr)}. This MVP has no payables ledger; the figure is presented as a note line only.`,
    MARGIN,
    y,
    { maxWidth: CONTENT_W },
  );
  statementsBlock(doc, y + 12, meta);
  footer(doc, meta);
  return doc;
}

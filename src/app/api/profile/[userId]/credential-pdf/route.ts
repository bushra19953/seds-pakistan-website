/**
 * WS3 — GET /api/profile/[userId]/credential-pdf?code=<certCode>
 *
 * Downloads a PDF verification sheet for one certificate: title, holder,
 * issuing authority, dates, verification URL and a QR code that opens the
 * existing /verify/[code] page. Used by the Credential Vault tab.
 *
 * Access: the member or an admin. Revoked certificates are refused.
 */
import { NextRequest, NextResponse } from 'next/server';
import { ensureAdminInitialized, getDb } from '@/lib/server/firebase-admin';
import { verifyAuthentication } from '@/lib/auth-middleware';
import { isFounder } from '@/lib/roles';
import { buildCertificateVerificationUrl } from '@/lib/profile-hub/telemetry';

export const dynamic = 'force-dynamic';
export const runtime = 'nodejs';

const ADMIN_ROLE_TOKENS = new Set(['superadmin', 'president_national']);

export async function GET(
  request: NextRequest,
  { params }: { params: Promise<{ userId: string }> },
) {
  const { userId } = await params;
  const code = new URL(request.url).searchParams.get('code');
  if (!userId || !code) return NextResponse.json({ error: 'User ID and code are required' }, { status: 400 });

  const authResult = await verifyAuthentication(request);
  if (!authResult.authenticated || !authResult.user) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
  }
  const isOwner = authResult.user.userId === userId;
  const isAdmin =
    isFounder(authResult.user.userId) ||
    ADMIN_ROLE_TOKENS.has(String(authResult.user.role || '').toLowerCase());
  if (!isOwner && !isAdmin) return NextResponse.json({ error: 'Forbidden' }, { status: 403 });

  if (!ensureAdminInitialized()) {
    return NextResponse.json({ error: 'Database connection failed' }, { status: 500 });
  }
  const db = getDb();
  if (!db) return NextResponse.json({ error: 'Database connection failed' }, { status: 500 });

  const snap = await db
    .collection('certificates')
    .where('userId', '==', userId)
    .where('code', '==', code)
    .limit(1)
    .get();
  if (snap.empty) return NextResponse.json({ error: 'Certificate not found' }, { status: 404 });
  const data = snap.docs[0].data() || {};
  if (data.status === 'revoked') {
    return NextResponse.json({ error: 'Certificate revoked' }, { status: 410 });
  }

  const baseUrl =
    process.env.NEXT_PUBLIC_SITE_URL ||
    process.env.NEXT_PUBLIC_BASE_URL ||
    new URL(request.url).origin;
  const verificationUrl = buildCertificateVerificationUrl(code, baseUrl);
  const title = String(data.title || data.achievement || data.eventName || 'Certificate');
  const holder = String(data.userName || 'SEDS Pakistan Member');
  const authority = String(data.issuingAuthority || data.issuerName || 'SEDS Pakistan');
  const issueDate = data.issueDate?.toDate?.() ? data.issueDate.toDate().toLocaleDateString() : 'Unknown';
  const certType = String(data.certificateType || 'Certificate');

  try {
    const QRCode = (await import('qrcode')).default;
    const qrDataUrl = await QRCode.toDataURL(verificationUrl, { margin: 1, width: 512 });

    const { jsPDF } = await import('jspdf');
    const doc = new jsPDF({ unit: 'pt', format: 'a4' });
    const W = 595;
    let y = 72;

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(22);
    doc.setTextColor(20, 20, 20);
    doc.text('SEDS PAKISTAN', W / 2, y, { align: 'center' });
    y += 28;
    doc.setFontSize(13);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(90, 90, 90);
    doc.text(certType, W / 2, y, { align: 'center' });
    y += 44;

    doc.setFontSize(20);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(20, 20, 20);
    const wrappedTitle = doc.splitTextToSize(title, W - 160);
    doc.text(wrappedTitle, W / 2, y, { align: 'center' });
    y += wrappedTitle.length * 26 + 8;

    doc.setFontSize(12);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(60, 60, 60);
    doc.text(`Awarded to: ${holder}`, W / 2, y, { align: 'center' });
    y += 22;
    doc.text(`Issued by: ${authority}`, W / 2, y, { align: 'center' });
    y += 22;
    doc.text(`Issued: ${issueDate}`, W / 2, y, { align: 'center' });
    y += 22;
    doc.setFont('courier', 'normal');
    doc.text(`Code: ${code}`, W / 2, y, { align: 'center' });
    y += 48;

    // QR block
    const qrSize = 160;
    doc.addImage(qrDataUrl, 'PNG', W / 2 - qrSize / 2, y, qrSize, qrSize);
    y += qrSize + 24;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(60, 60, 60);
    doc.text('Scan to verify this certificate:', W / 2, y, { align: 'center' });
    y += 18;
    doc.setTextColor(30, 90, 200);
    doc.textWithLink(verificationUrl, W / 2, y, { align: 'center', url: verificationUrl });

    // Footer
    doc.setFontSize(9);
    doc.setTextColor(120, 120, 120);
    doc.text('Generated by the SEDS Pakistan Member Profile Hub.', W / 2, 820, { align: 'center' });

    const bytes = Buffer.from(doc.output('arraybuffer'));
    return new NextResponse(bytes, {
      headers: {
        'Content-Type': 'application/pdf',
        'Content-Disposition': `attachment; filename="seds-certificate-${code}.pdf"`,
        'Content-Length': String(bytes.length),
      },
    });
  } catch (e) {
    console.error('[credential-pdf:route] PDF generation failed:', e instanceof Error ? e.message : e);
    return NextResponse.json({ error: 'PDF generation failed' }, { status: 500 });
  }
}

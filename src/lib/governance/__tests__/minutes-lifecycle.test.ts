import { buildMinutesDraft, type BuildMinutesDraftInput } from "../minutes-draft";
import {
  MINUTES_CIRCULATION_WINDOW_MS,
  MinutesError,
  applyMinutesEdit,
  approveMinutes,
  canTransitionMinutes,
  circulateMinutes,
  createMinutesRecord,
  isCirculationOverdue,
  retentionUntilFor,
  signMinutes,
  type MinutesRecord,
} from "../minutes-lifecycle";

const CLOSED = new Date("2026-10-21T11:00:00Z");
const DAY = 24 * 60 * 60 * 1000;

const fixture: BuildMinutesDraftInput = {
  meeting: {
    id: "mtg_1",
    bodyId: "body_board",
    bodyType: "board",
    consentId: "consent_granted",
    quorumRequired: 5,
    quorumVerifiedAt: "2026-10-21T10:05:00.000Z",
    quorumVerifiedBy: "uid_chair",
    closedAt: "2026-10-21T11:00:00.000Z",
  },
  attendance: [
    { uid: "uid_chair", displayName: "Chair One", mode: "in_person", isPresent: true },
    { uid: "uid_a", displayName: "Member A", mode: "in_person", isPresent: true },
    { uid: "uid_b", displayName: "Member B", mode: "electronic", isPresent: true },
    { uid: "uid_c", displayName: "Member C", mode: "electronic", isPresent: true },
    { uid: "uid_d", displayName: "Member D", mode: "in_person", isPresent: true },
    { uid: "uid_e", displayName: "Member E", mode: "absent", isPresent: false },
  ],
  motions: [
    {
      id: "motion_1",
      text: "Approve the annual budget",
      decisionClassId: "class_budget",
      proposerUid: "uid_a",
      method: "electronic_poll",
      status: "closed_passed",
      consentId: "consent_granted",
    },
  ],
  ballots: [{ motionId: "motion_1", voterUid: "uid_a", choice: "for" }],
  secretTotals: [],
  consents: [
    { consentId: "consent_granted", matter: "Budget spend", outcome: "granted", decidedAt: "2026-10-20T09:00:00.000Z" },
  ],
};

function freshRecord(): MinutesRecord {
  return createMinutesRecord({
    id: "min_1",
    meetingId: "mtg_1",
    bodyId: "body_board",
    fields: buildMinutesDraft(fixture),
    meetingClosedAt: CLOSED,
  });
}

const circulatedRecord = () => circulateMinutes(freshRecord(), new Date(CLOSED.getTime() + DAY));
const approvedRecord = () =>
  approveMinutes(circulatedRecord(), {
    approvalMotionId: "motion_approve_minutes",
    approvedInMeetingId: "mtg_2",
    approvalMotionStatus: "closed_passed",
    at: new Date(CLOSED.getTime() + 14 * DAY),
  });

const PDF = {
  driveFileId: "drive_1",
  driveLink: "https://drive.example/min_1.pdf",
  sha256: "abc123",
  fileName: "minutes_board_mtg_1_20261104.pdf",
  uploadedAt: new Date("2026-11-04T12:00:00Z"),
};

describe("minutes creation (ws-a §6.3 step 1)", () => {
  it("starts auto_drafted, generated by the system, due exactly 7 days after close", () => {
    const rec = freshRecord();
    expect(rec.status).toBe("auto_drafted");
    expect(rec.generatedBy).toBe("system");
    expect(rec.circulationDueAt.getTime() - CLOSED.getTime()).toBe(MINUTES_CIRCULATION_WINDOW_MS);
    expect(rec.circulationDueAt.getTime() - CLOSED.getTime()).toBe(7 * DAY);
    expect(rec.retentionUntil).toBeNull();
    expect(rec.pdf).toBeNull();
  });
});

describe("minutes transitions (ws-a §3.7 status enum)", () => {
  it("allows the legal path and refuses skips and backwards moves", () => {
    expect(canTransitionMinutes("auto_drafted", "circulated")).toBe(true);
    expect(canTransitionMinutes("auto_drafted", "approved")).toBe(false);
    expect(canTransitionMinutes("circulated", "signed_locked")).toBe(false);
    expect(canTransitionMinutes("signed_locked", "in_edit")).toBe(false);
  });
});

describe("minutes edit guard (ws-a §4.6)", () => {
  it("accepts supplementaryNotes and corrections, and the first edit flips to in_edit", () => {
    const edited = applyMinutesEdit(
      freshRecord(),
      {
        supplementaryNotes: "Venue changed at short notice.",
        corrections: [{ field: "fieldMotions", note: "Typo in title noted", by: "ngs", at: CLOSED }],
      },
      { by: "ngs", at: CLOSED },
    );
    expect(edited.status).toBe("in_edit");
    expect(edited.supplementaryNotes).toBe("Venue changed at short notice.");
    expect(edited.corrections).toHaveLength(1);
    expect(edited.editedBy).toBe("ngs");
  });

  it("refuses a patch carrying a generated field with 422 generated_field_immutable", () => {
    expect(() =>
      applyMinutesEdit(freshRecord(), { fieldVoting: [] }, { by: "ngs", at: CLOSED }),
    ).toThrow(MinutesError);
    try {
      applyMinutesEdit(freshRecord(), { fieldAttendees: {} }, { by: "ngs", at: CLOSED });
      throw new Error("should have thrown");
    } catch (e) {
      expect((e as MinutesError).code).toBe("generated_field_immutable");
      expect((e as MinutesError).status).toBe(422);
    }
  });

  it("refuses a patch to identity/status fields as immutable_field", () => {
    expect(() =>
      applyMinutesEdit(freshRecord(), { status: "signed_locked" }, { by: "ngs", at: CLOSED }),
    ).toThrow(/immutable_field|Minutes field status cannot be changed/);
  });
});

describe("minutes circulation and overdue (ws-a §6.6 T2)", () => {
  it("circulate stamps circulatedAt and cannot run twice", () => {
    const rec = circulatedRecord();
    expect(rec.status).toBe("circulated");
    expect(rec.circulatedAt).not.toBeNull();
    expect(() => circulateMinutes(rec, new Date())).toThrow(MinutesError);
  });

  it("overdue only while auto_drafted/in_edit and strictly past the due time", () => {
    const rec = freshRecord();
    expect(isCirculationOverdue(rec, rec.circulationDueAt)).toBe(false);
    expect(isCirculationOverdue(rec, new Date(rec.circulationDueAt.getTime() + 1))).toBe(true);
    const circ = circulatedRecord();
    expect(isCirculationOverdue(circ, new Date(circ.circulationDueAt.getTime() + 30 * DAY))).toBe(false);
  });
});

describe("minutes approval and signing (ws-a §4.6, §6.3; test case 15)", () => {
  it("approving before circulation is refused", () => {
    expect(() =>
      approveMinutes(freshRecord(), {
        approvalMotionId: "m",
        approvedInMeetingId: "mtg_2",
        approvalMotionStatus: "closed_passed",
        at: new Date(),
      }),
    ).toThrow(MinutesError);
  });

  it("approval by a motion that did not close passed is 422 minutes_not_approved", () => {
    try {
      approveMinutes(circulatedRecord(), {
        approvalMotionId: "m",
        approvedInMeetingId: "mtg_2",
        approvalMotionStatus: "closed_failed",
        at: new Date(),
      });
      throw new Error("should have thrown");
    } catch (e) {
      expect((e as MinutesError).code).toBe("minutes_not_approved");
      expect((e as MinutesError).status).toBe(422);
    }
  });

  it("signing before approval returns 422 minutes_not_approved", () => {
    try {
      signMinutes(circulatedRecord(), { signedBy: "ngs", at: new Date(), pdf: PDF });
      throw new Error("should have thrown");
    } catch (e) {
      expect((e as MinutesError).code).toBe("minutes_not_approved");
      expect((e as MinutesError).status).toBe(422);
    }
  });

  it("after approval, signing locks and sets retentionUntil to signedAt + 10 years", () => {
    const signedAt = new Date("2026-11-04T12:00:00Z");
    const signed = signMinutes(approvedRecord(), { signedBy: "ngs", at: signedAt, pdf: PDF });
    expect(signed.status).toBe("signed_locked");
    expect(signed.signedBy).toBe("ngs");
    expect(signed.retentionUntil).toEqual(new Date("2036-11-04T12:00:00Z"));
    expect(retentionUntilFor(signedAt)).toEqual(signed.retentionUntil);
    expect(signed.pdf?.sha256).toBe("abc123");
  });

  it("a later edit of signed minutes is refused with 409 minutes_locked", () => {
    const signed = signMinutes(approvedRecord(), {
      signedBy: "ngs",
      at: new Date("2026-11-04T12:00:00Z"),
      pdf: PDF,
    });
    try {
      applyMinutesEdit(signed, { supplementaryNotes: "late note" }, { by: "ngs", at: new Date() });
      throw new Error("should have thrown");
    } catch (e) {
      expect((e as MinutesError).code).toBe("minutes_locked");
      expect((e as MinutesError).status).toBe(409);
    }
  });
});
